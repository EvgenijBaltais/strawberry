<h1>Политика использования файлов cookie для сайта strawberry</h1>

<p>
<b>1. Что такое файлы cookie?</b>
<br><br>
Файлы cookie — это небольшие текстовые файлы, которые сохраняются на вашем устройстве (компьютере, планшете, смартфоне) когда вы посещаете наш сайт. Они широко используются для обеспечения корректной и эффективной работы сайтов, а также для предоставления владельцам сайта информации о поведении пользователей.
<br>
Файлы cookie не являются программами и не могут содержать вирусы или вредоносный код.
</p>
<p>
<b>2. Как мы используем файлы cookie?</b><br><br>
На сайте strawberry мы используем файлы cookie для следующих целей:
<br><br>
Необходимые: Эти файлы cookie абсолютно необходимы для работы сайта и обеспечения его базовых функций (например, запоминание добавленных товаров в корзину, безопасный вход в личный кабинет). Без этих файлов cookie мы не сможем предоставить вам запрашиваемые услуги.
<br><br>
Функциональные: Эти файлы cookie позволяют сайту запоминать сделанные вами выборы (такие как имя пользователя, язык или регион) и предоставлять улучшенные, более персонализированные функции.
<br><br>
Аналитические/Производительности: Эти файлы cookie помогают нам понимать, как посетители взаимодействуют с нашим сайтом (например, какие страницы посещают чаще всего, возникают ли ошибки при загрузке страниц). Эта информация собирается в агрегированной, обезличенной форме и помогает нам улучшать работу сайта.
<br><br>
Рекламные/Отслеживающие: Эти файлы cookie используются для отслеживания посещений нашего и других сайтов. Они могут использоваться нами или нашими рекламными партнерами для показа вам релевантной рекламы на основе ваших интересов, а также для оценки эффективности рекламных кампаний.
</p>
<p>
<b>3. Какие типы файлов cookie мы используем?</b><br><br>
Ниже приведены более подробные сведения о файлах cookie, которые мы используем.
</p>


<b>Необходимые:</b><br><br>

<b>session_id</b><br>
Назначение: поддержание сессии пользователя (например, корзина покупок, авторизация).<br>
Провайдер: strawberry.<br>
Срок хранения: Сессия.
<br><br>

<b>csrf_token</b><br>
Назначение: защита от межсайтовой подделки запроса.<br>
Провайдер: strawberry.<br>
Срок хранения: Сессия.<br><br>

<b>cookie_info</b><br>
Назначение: запоминание вашего согласия с использованием cookie.<br>
Провайдер: strawberry.<br>
Срок хранения: 30 дней.<br><br>

<b>Аналитические:</b><br><br>	
<b>yandex_metrika_*</b><br>
Сбор анонимной статистики для сервиса Яндекс.Метрика.<br>
Срок хранения: до 1 года.

